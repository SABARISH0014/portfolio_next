const QUICK_COMMANDS = ["help", "about", "skills", "projects", "download", "resume", "clear", "exit"];

export function TerminalMode() {
  const { isTerminalMode, setTerminalMode } = useTerminal();
  const [input, setInput] = useState("");
  const [cmdHistory, setCmdHistory] = useState<string[]>([]);
  const [historyIndex, setHistoryIndex] = useState(-1);
  const [history, setHistory] = useState<HistoryItem[]>([
    { command: "system", output: "Portfolio OS v2.1.0 -- initializing..." },
    { command: "system", output: "Type 'help' for available commands or tap the quick pills below." }
  ]);
  const inputRef = useRef<HTMLInputElement>(null);
  const bottomRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (isTerminalMode) {
      inputRef.current?.focus();
    }
  }, [isTerminalMode]);

  useEffect(() => {
    if (!isTerminalMode) return;

    const handleGlobalKeyDown = (e: KeyboardEvent) => {
      if (e.key === "Escape") {
        setTerminalMode(false);
      }
    };

    window.addEventListener("keydown", handleGlobalKeyDown);
    return () => window.removeEventListener("keydown", handleGlobalKeyDown);
  }, [isTerminalMode, setTerminalMode]);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [history]);

  const triggerDownload = useCallback(() => {
    const blob = new Blob([PROJECTS_CONTENT], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "projects.txt";
    a.click();
    URL.revokeObjectURL(url);
  }, []);

  const triggerResumeDownload = useCallback(() => {
    const a = document.createElement("a");
    a.href = "/resume.pdf";
    a.download = "Sabarish_P_Resume.pdf";
    a.click();
  }, []);

  const executeCommand = useCallback(
    (rawCommand: string) => {
      const cmd = rawCommand.trim().toLowerCase();
      const raw = rawCommand.trim();

      let output: string | React.ReactNode = "";

      switch (cmd) {
        case "help":
          output = HELP_OUTPUT;
          break;
        case "about":
        case "whoami":
          output = ABOUT_OUTPUT;
          break;
        case "skills":
          output = SKILLS_OUTPUT;
          break;
        case "projects":
          output = PROJECTS_OUTPUT;
          break;
        case "download": {
          triggerDownload();
          output = "✓ projects.txt downloaded successfully.";
          break;
        }
        case "resume": {
          triggerResumeDownload();
          output = "✓ Sabarish_P_Resume.pdf downloading...";
          break;
        }
        case "clear":
          setHistory([]);
          setInput("");
          return;
        case "exit":
          setTerminalMode(false);
          setInput("");
          return;
        case "":
          output = "";
          break;
        default:
          output = `Command not found: ${cmd}. Type 'help' for a list of commands.`;
      }

      if (raw) {
        setCmdHistory((prev) => [raw, ...prev]);
        setHistoryIndex(-1);
      }

      setHistory((prev) => [...prev, { command: raw || " ", output }]);
      setInput("");
    },
    [setTerminalMode, triggerDownload, triggerResumeDownload]
  );

  if (!isTerminalMode) return null;

  const handleKeyDown = (e: React.KeyboardEvent<HTMLInputElement>) => {
    if (e.key === "ArrowUp") {
      e.preventDefault();
      const newIndex = Math.min(historyIndex + 1, cmdHistory.length - 1);
      setHistoryIndex(newIndex);
      setInput(cmdHistory[newIndex] ?? "");
    } else if (e.key === "ArrowDown") {
      e.preventDefault();
      const newIndex = Math.max(historyIndex - 1, -1);
      setHistoryIndex(newIndex);
      setInput(newIndex === -1 ? "" : (cmdHistory[newIndex] ?? ""));
    }
  };

  const handleFormSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    executeCommand(input);
  };

  return (
    <div
      className="fixed inset-0 z-[1000] bg-black font-mono text-green-400 overflow-y-auto p-4 pb-10 sm:p-6 sm:pb-10"
      onClick={() => inputRef.current?.focus()}
    >
      <div className="max-w-3xl mx-auto space-y-1">
        {/* Sticky top bar with exit button */}
        <div className="sticky top-0 z-10 -mx-4 -mt-4 mb-4 flex items-center justify-between border-b border-green-500/20 bg-black/95 px-4 py-2.5 backdrop-blur-md sm:-mx-6 sm:-mt-6">
          <div className="flex items-center gap-2 text-xs text-green-400">
            <span className="h-2 w-2 rounded-full bg-green-500 animate-pulse" />
            <span className="font-semibold">visitor@sabarish:~</span>
          </div>
          <button
            type="button"
            onClick={(e) => {
              e.stopPropagation();
              setTerminalMode(false);
            }}
            className="rounded border border-green-500/30 bg-green-950/40 px-2.5 py-1 text-xs text-green-300 transition-colors hover:bg-green-500/20 hover:text-green-200"
          >
            [Exit CLI ✕]
          </button>
        </div>

        {/* Mobile Quick Tap Command Pills */}
        <div className="flex flex-wrap gap-1.5 sm:hidden mb-4 pt-1">
          {QUICK_COMMANDS.map((cmd) => (
            <button
              key={cmd}
              type="button"
              onClick={(e) => {
                e.stopPropagation();
                executeCommand(cmd);
              }}
              className="rounded-md border border-green-500/30 bg-green-950/40 px-2.5 py-1 text-xs text-green-300 transition-colors active:bg-green-500/20"
            >
              {cmd}
            </button>
          ))}
        </div>

        {/* Command Output History */}
        {history.map((item, i) => (
          <div key={i} className="mb-3">
            {item.command !== "system" && (
              <div className="flex gap-2 items-center">
                <span className="text-green-600 select-none">visitor@sabarish:~$</span>
                <span className="text-green-300">{item.command}</span>
              </div>
            )}
            {item.command === "system" && (
              <div className="text-green-600/80 text-sm">{item.output}</div>
            )}
            {item.command !== "system" && item.output !== "" && (
              <div className="mt-1 whitespace-pre-wrap text-green-400/90 leading-6 text-sm overflow-x-auto">
                {item.output}
              </div>
            )}
          </div>
        ))}

        {/* Command input prompt */}
        <form onSubmit={handleFormSubmit} className="flex gap-2 items-center mt-2">
          <span className="text-green-600 select-none">visitor@sabarish:~$</span>
          <input
            ref={inputRef}
            type="text"
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={handleKeyDown}
            className="flex-1 bg-transparent outline-none border-none text-green-300 caret-green-400 text-base sm:text-sm"
            autoFocus
            spellCheck={false}
            autoComplete="off"
          />
        </form>
        <div ref={bottomRef} />
      </div>
    </div>
  );
}
